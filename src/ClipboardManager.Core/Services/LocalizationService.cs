public record LanguageOption(string Code, string NativeName, string EnglishName);

/// <summary>
/// Centralized localization service providing multi-language support (English, Vietnamese, Chinese, Japanese, Korean, Spanish, French, German, Russian, Portuguese).
/// </summary>
