    private static string _currentLanguage = "en";

    public static event Action? LanguageChanged;

    public static string CurrentLanguage
    {
        get => _currentLanguage;
        set => SetLanguage(value);
    }

    public static void SetLanguage(string? code)
    {
        var normalized = NormalizeLanguageCode(code);
        if (_currentLanguage == normalized) return;
        _currentLanguage = normalized;
        LanguageChanged?.Invoke();
    }

    public static string NormalizeLanguageCode(string? code)
    {
        if (string.IsNullOrWhiteSpace(code)) return "en";
        var c = code.Trim().ToLowerInvariant();
        if (c.StartsWith("vi")) return "vi";
        if (c.StartsWith("zh")) return "zh";
        if (c.StartsWith("ja")) return "ja";
        if (c.StartsWith("ko")) return "ko";
        if (c.StartsWith("es")) return "es";
        if (c.StartsWith("fr")) return "fr";
        if (c.StartsWith("de")) return "de";
        if (c.StartsWith("ru")) return "ru";
        if (c.StartsWith("pt")) return "pt";
        return "en";
    }

    public static string Get(string key, params object[] args)
    {
        if (string.IsNullOrEmpty(key)) return "";

        string? value = null;
        if (Translations.TryGetValue(_currentLanguage, out var langDict))
        {
            langDict.TryGetValue(key, out value);
        }

        if (value is null && _currentLanguage != "en" && Translations.TryGetValue("en", out var enDict))
        {
            enDict.TryGetValue(key, out value);
        }

        value ??= key;

        if (args is { Length: > 0 })
        {
            try
            {
                return string.Format(value, args);
            }
            catch (FormatException)
            {
                return value;
            }
        }
        return value;
    }

    public static string T(string key, params object[] args) => Get(key, args);

